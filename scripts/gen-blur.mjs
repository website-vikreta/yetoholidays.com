// Writes lib/blur.generated.ts: a tiny blurred JPEG (data URI) for every
// Unsplash photo id used in lib/data.ts. Run after adding photos:
//   node scripts/gen-blur.mjs
import { readFileSync, writeFileSync } from "node:fs";
// sharp ships with Next.js; it strips Unsplash metadata so each placeholder stays a few hundred bytes.
import sharp from "sharp";

const ids = [
  ...new Set([...readFileSync("lib/data.ts", "utf8").matchAll(/U\("([0-9a-z-]+)"/g)].map((m) => m[1])),
];

const entries = [];
for (const id of ids) {
  const res = await fetch(`https://images.unsplash.com/photo-${id}?auto=format&fit=crop&w=16&q=30`);
  if (!res.ok) {
    console.warn(`skip ${id}: HTTP ${res.status}`);
    continue;
  }
  const tiny = await sharp(Buffer.from(await res.arrayBuffer()))
    .resize(8, 6, { fit: "cover" })
    .webp({ quality: 40 })
    .toBuffer();
  entries.push(`  "${id}": "data:image/webp;base64,${tiny.toString("base64")}",`);
}

writeFileSync(
  "lib/blur.generated.ts",
  `// Generated by scripts/gen-blur.mjs. Do not edit by hand.\nexport const BLUR: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`wrote ${entries.length} of ${ids.length} placeholders`);
